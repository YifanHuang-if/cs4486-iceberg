KEYS = sorted(NARRATIVES, key=len, reverse=True)
PATTERNS = [(k, re.compile(rf"^{re.escape(k)}(?=[\s\u3000]|$)")) for k in KEYS]


def match_key(text: str) -> str | None:
    for key, pattern in PATTERNS:
        if pattern.match(text):
            return key
    return None


def main() -> int:
    document = Document(PATH)
    paragraphs = list(document.paragraphs)

    current = None
    inserted = 0
    for index, paragraph in enumerate(paragraphs):
        text = paragraph.text.strip()
        if paragraph.style.name.startswith("Heading"):
            current = match_key(text)
            continue
        if current and text.startswith("术语说明"):
            body = NARRATIVES[current]
            head = paragraph.insert_paragraph_before()
            run = head.add_run("这一步在做什么（通俗版）")
            run.bold = True
            run.font.size = Pt(9.5)
            run.font.color.rgb = ACCENT
            head.paragraph_format.space_before = Pt(4)
            head.paragraph_format.space_after = Pt(2)

            body_paragraph = paragraph.insert_paragraph_before()
            body_run = body_paragraph.add_run(body)
            body_run.font.size = Pt(9.5)
            body_run.font.color.rgb = GREY
            body_paragraph.paragraph_format.left_indent = Pt(12)
            body_paragraph.paragraph_format.space_after = Pt(4)
            inserted += 1
            current = None

    print(f"narratives inserted: {inserted}/{len(NARRATIVES)}")
    document.save(PATH)
    print(f"saved: {PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
