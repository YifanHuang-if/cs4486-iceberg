def write_block(insert_before, document, entries) -> None:
    def make(text_runs, indent=12):
        paragraph = (insert_before.insert_paragraph_before()
                     if insert_before is not None else document.add_paragraph())
        for text, bold, colour, size in text_runs:
            run = paragraph.add_run(text)
            run.bold = bold
            run.font.size = Pt(size)
            run.font.color.rgb = colour
        paragraph.paragraph_format.left_indent = Pt(indent)
        paragraph.paragraph_format.space_after = Pt(2)
        return paragraph

    make([("术语说明（通俗版）", True, ACCENT, 10)], indent=0)
    for term, explanation in entries:
        make([(f"{term}：", True, GREY, 9), (explanation, False, GREY, 9)])


def main() -> int:
    shutil.copy2(BACKUP, PATH)
    document = Document(PATH)

    for anchor_text, entries in PAIRS:
        anchor = None
        for paragraph in document.paragraphs:
            if paragraph.text.strip().startswith(anchor_text):
                anchor = paragraph
                break
        if anchor is None:
            print(f"  missing anchor: {anchor_text}")
            continue
        write_block(anchor, document, entries)
        print(f"  inserted before: {anchor_text}")

    write_block(None, document, S9)
    print("  appended final block")

    document.save(PATH)
    print(f"saved: {PATH}")
    return 0


